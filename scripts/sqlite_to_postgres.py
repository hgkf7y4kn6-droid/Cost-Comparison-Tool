#!/usr/bin/env python3
"""Turns the single-tenant SQLite records database (sales_hub.db) into SQL for
the multi-tenant Postgres schema. Standard library only; nothing is written to
either database by this script. Review the output, then apply it as the
database owner:

    python scripts/sqlite_to_postgres.py --db /var/data/sales_hub.db \\
        --org "Office Basics" --manager boss@example.com --member ana@example.com \\
        > import.sql
    psql "$ADMIN_URL" -v ON_ERROR_STOP=1 -f import.sql

Safe to re-run: the org id is derived from the org name and records are
upserted. Everyone who owns a record is added to the org as a rep (managers
and extra members come from the flags). A summary goes to stderr.
"""
import argparse
import json
import re
import sqlite3
import sys
import uuid
from typing import Dict, Iterable, List, Tuple

EMAIL_RE = re.compile(r"^[^@\s,']+@[^@\s,']+\.[^@\s,']+$")
ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
KINDS = ("accounts", "leads")


def q(value: str) -> str:
    """A Postgres string literal (standard_conforming_strings is switched on in the output)."""
    if "\x00" in value:
        raise ValueError("NUL characters can't be stored in Postgres text.")
    return "'" + value.replace("'", "''") + "'"


def org_id_for(name: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "vectorsales:org:" + name.strip().lower()))


def read_records(db_path: str) -> List[Tuple[str, str, str, str]]:
    db = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    try:
        return db.execute("select kind, id, owner, data from records order by kind, id").fetchall()
    finally:
        db.close()


def build_sql(records: Iterable[Tuple[str, str, str, str]], org_name: str,
              managers: Iterable[str] = (), members: Iterable[str] = ()) -> Tuple[str, Dict[str, int]]:
    org = org_id_for(org_name)
    roles: Dict[str, str] = {}
    for email in members:
        roles[email.strip().lower()] = "rep"
    for email in managers:
        roles[email.strip().lower()] = "manager"

    rows, skipped = [], []
    for kind, rid, owner, data in records:
        owner = (owner or "").strip().lower()
        try:
            if kind not in KINDS:
                raise ValueError(f"unknown kind {kind!r}")
            if not ID_RE.match(rid or ""):
                raise ValueError("invalid id")
            if not EMAIL_RE.match(owner):
                raise ValueError(f"owner {owner!r} isn't an email")
            json.loads(data)  # must be valid JSON
        except ValueError as e:
            skipped.append(f"{kind}/{rid}: {e}")
            continue
        roles.setdefault(owner, "rep")
        rows.append((kind, rid, owner, data))

    for email in roles:
        if not EMAIL_RE.match(email):
            raise ValueError(f"Not an email address: {email!r}")

    out = [
        "-- Generated by scripts/sqlite_to_postgres.py. Review before applying.",
        "set standard_conforming_strings = on;",
        "begin;",
        f"insert into orgs (id, name) values ({q(org)}, {q(org_name.strip())}) on conflict (id) do nothing;",
    ]
    for email, role in sorted(roles.items()):
        out.append(f"insert into memberships (email, org_id, role) values ({q(email)}, {q(org)}, {q(role)})"
                   f" on conflict (email) do update set role = excluded.role"
                   f" where memberships.org_id = excluded.org_id;")
    for kind, rid, owner, data in rows:
        out.append(f"insert into records (org_id, kind, id, owner, data) values ({q(org)}, {q(kind)}, {q(rid)}, {q(owner)}, {q(data)}::jsonb)"
                   f" on conflict (org_id, kind, id) do update set owner = excluded.owner, data = excluded.data, updated_at = now();")
    out.append("commit;")
    stats = {"records": len(rows), "skipped": len(skipped), "members": len(roles)}
    if skipped:
        out.insert(1, "".join(f"-- SKIPPED {s}\n" for s in skipped).rstrip("\n"))
    return "\n".join(out) + "\n", stats


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", required=True, help="path to sales_hub.db")
    ap.add_argument("--org", required=True, help="organization name to create")
    ap.add_argument("--manager", action="append", default=[], help="manager email (repeatable)")
    ap.add_argument("--member", action="append", default=[], help="extra member email (repeatable)")
    args = ap.parse_args(argv)
    sql, stats = build_sql(read_records(args.db), args.org, args.manager, args.member)
    sys.stdout.write(sql)
    print(f"{stats['records']} records, {stats['members']} members, {stats['skipped']} skipped "
          f"(org id {org_id_for(args.org)})", file=sys.stderr)
    return 1 if stats["skipped"] else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
